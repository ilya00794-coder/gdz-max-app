/** Та же нормализация, что в curriculum.js/subjects.js. */
function normalize(subject) {
  return String(subject || "").trim().toLowerCase().replace(/ё/g, "е");
}

/**
 * Текст предметных правил для system-блока. Пустая строка — блока нет,
 * solveTask в этом случае третий блок не добавляет вовсе.
 */
export function subjectRules(subject) {
  const keys = SUBJECT_TO_BLOCKS[normalize(subject)] ?? [];
  return keys.map((k) => BLOCKS[k]).filter(Boolean).join("\n\n");
}

