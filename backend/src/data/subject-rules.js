/** Та же нормализация, что в curriculum.js/subjects.js. */
function normalize(subject) {
  return String(subject || "").trim().toLowerCase().replace(/ё/g, "е");
}

/**
 * Блоки наглядности — класс-зависимые: началка (1–4) не возит критерии
 * треугольников, а математика 5–6 (наглядная геометрия внутри предмета
 * «математика») и геометрия 7+ видят оба, чтобы не терять ни чертежи,
 * ни началочные виды (числовой луч, прямоугольник — уместны и там).
 */
function visualBlocksFor(subject, grade) {
  const subj = normalize(subject);
  const g = Number(grade);
  if (subj === "математика") {
    return g >= 1 && g <= 4 ? ["наглядность-началка"] : ["наглядность-началка", "наглядность-геометрия"];
  }
  if (subj === "геометрия") return ["наглядность-геометрия", "наглядность-началка"];
  return [];
}

/**
 * Текст предметных правил для system-блока. Пустая строка — блока нет,
 * solveTask в этом случае третий блок не добавляет вовсе.
 * grade нужен для класс-зависимой наглядности; без него (старые вызовы
 * канареек) наглядность подмешивается целиком, как до сплита.
 */
export function subjectRules(subject, grade = null) {
  const keys = SUBJECT_TO_BLOCKS[normalize(subject)] ?? [];
  const visual = grade === null
    ? (["математика", "геометрия"].includes(normalize(subject)) ? ["наглядность-началка", "наглядность-геометрия"] : [])
    : visualBlocksFor(subject, grade);
  return [...keys, ...visual].map((k) => BLOCKS[k]).filter(Boolean).join("\n\n");
}

// Только для канареек: даёт тестам подложить временный блок, не трогая прод.
/** Есть ли у предмета ОСОЗНАННАЯ запись о блоках (пусть пустая) — для стартовой проверки полноты. */
export function hasBlockEntry(subject) {
  return normalize(subject) in SUBJECT_TO_BLOCKS;
}

