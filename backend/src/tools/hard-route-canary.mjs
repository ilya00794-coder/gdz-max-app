// Юнит-канарейка isHardInequality (роутинг трудного класса, инцидент №40).
// Первый заход был разовым (11 кейсов в a34172b, файл не закоммичен) —
// закреплено файлом 12.09 после живого пропуска «/((x+3)(x+2)(x-3))».
// Запуск: node backend/src/tools/hard-route-canary.mjs (из корня репо).
import { isHardInequality } from "../services/solver.js";

const CASES = [
  // --- позитивы: знак неравенства И переменная в знаменателе ---
  ["\\frac{9x^3+9x+7}{3x^3+2x-1} \\geq 0", true, "LaTeX дробь (живой кейс №40)"],
  ["1/(x+2) > 3", true, "плоская дробь, скобка"],
  ["(x^2+1)/((x+3)(x+2)(x-3)) ≥ 0", true, "знаменатель-произведение скобок (живой пропуск 12.09)"],
  ["\\frac{2}{y-1} \\le 5", true, "LaTeX, y в знаменателе"],
  ["5/2y < 1", true, "цифры перед буквой в знаменателе"],
  ["Решите неравенство: \\dfrac{x}{x-4} \\leq 2", true, "dfrac"],
  // --- негативы: обычные дроби/уравнения/числовые знаменатели ---
  ["\\frac{x}{3} + \\frac{x-2}{5} = 2", false, "уравнение без знака неравенства"],
  ["\\frac{x-1}{4} \\geq 2", false, "числовой знаменатель LaTeX"],
  ["2x + 5 > 13", false, "неравенство без дробей"],
  ["x/2 ≥ 7", false, "числовой знаменатель плоский"],
  ["Решите уравнение \\frac{1}{x} = 5", false, "дробь с переменной, но уравнение"],
  ["3,5 > 1/4", false, "числовая дробь"],
  ["x^2 - 4 ≤ 0", false, "квадратное неравенство без дробей"],
];

let fail = 0;
for (const [text, want, name] of CASES) {
  const got = isHardInequality(text);
  console.log(`${got === want ? "✅" : "❌"} ${name}: ${JSON.stringify(text).slice(0, 70)} → ${got}`);
  if (got !== want) fail++;
}
console.log(fail ? `FAIL: ${fail}` : `OK: ${CASES.length}/${CASES.length}`);
process.exit(fail ? 1 : 0);
